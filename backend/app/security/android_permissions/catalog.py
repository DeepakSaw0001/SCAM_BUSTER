def get_permission_metadata(perm: str, target_sdk: Optional[int] = None) -> AndroidPermissionMetadata:
    """
    Retrieve authoritative metadata for a permission string.
    If permission is unrecognized, returns an UNKNOWN category descriptor with objective wording.
    """
    clean = perm.strip()
    if clean in PERMISSION_CATALOG:
        meta = PERMISSION_CATALOG[clean]
        # Adjust runtime permission requirement if target SDK is known
        is_runtime = is_runtime_permission_at_target(
            clean,
            target_sdk,
            meta.protection_level == PROTECTION_DANGEROUS
        )
        return AndroidPermissionMetadata(
            permission=meta.permission,
            short_name=meta.short_name,
            category=meta.category,
            sensitivity=meta.sensitivity,
            protection_level=meta.protection_level,
            runtime_permission=is_runtime,
            added_api_level=meta.added_api_level,
            deprecated_api_level=meta.deprecated_api_level,
            description=meta.description,
            privacy_impact=meta.privacy_impact,
            user_consent_required=meta.user_consent_required,
            why_it_matters=meta.why_it_matters,
        )

    # Clean short display name
    short = clean.split(".")[-1] if "." in clean else clean

    return AndroidPermissionMetadata(
        permission=clean,
        short_name=short,
        category=CAT_UNKNOWN,
        sensitivity=SENSITIVITY_LOW,
        protection_level=PROTECTION_UNKNOWN,
        runtime_permission=False,
        added_api_level=0,
        deprecated_api_level=None,
        description="Permission was not recognized by the current permission catalog.",
        privacy_impact=[],
        user_consent_required=False,
        why_it_matters="Custom, third-party library, or vendor-defined permission not part of standard AOSP definitions.",
    )


def is_high_impact_permission(perm: str) -> bool:
    """Return True if permission can grant elevated system control or deep private data access."""
    return perm.strip() in HIGH_IMPACT_PERMISSIONS
