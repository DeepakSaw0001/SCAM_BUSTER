@dataclass
class AndroidPermissionMetadata:
    permission: str
    short_name: str
    category: str
    sensitivity: str
    protection_level: str
    runtime_permission: bool
    added_api_level: int
    deprecated_api_level: Optional[int]
    description: str
    privacy_impact: List[str] = field(default_factory=list)
    user_consent_required: bool = False
    why_it_matters: str = ""

    def to_dict(self) -> Dict[str, any]:
        return {
            "permission": self.permission,
            "short_name": self.short_name,
            "category": self.category,
            "sensitivity": self.sensitivity,
            "protection_level": self.protection_level,
            "runtime_permission": self.runtime_permission,
            "added_api_level": self.added_api_level,
            "deprecated_api_level": self.deprecated_api_level,
            "description": self.description,
            "privacy_impact": self.privacy_impact,
            "user_consent_required": self.user_consent_required,
            "why_it_matters": self.why_it_matters,
        }


